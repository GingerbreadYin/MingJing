def dump(name,value):
    path=ROOT/'data'/name
    path.parent.mkdir(exist_ok=True)
    path.write_text(json.dumps(value,ensure_ascii=False,indent=2),encoding='utf-8')


def main():
    originals=json.loads((ROOT/'baseline/rag/chunks.json').read_text(encoding='utf-8'))
    grouped={}
    for chunk in originals:
        doc=grouped.setdefault(chunk['document_id'],{'id':chunk['document_id'],'title':chunk['source'],'source':'原项目演示政策','facts':[]})
        doc['facts'].append({'id':chunk['id'],'text':chunk['text']})
    docs=list(grouped.values())
    dev,held=[] ,[]
    for i,(title,a,b,q1,q2,q3) in enumerate(POLICIES,1):
        did=f'demo-{i:02d}'
        docs.append({'id':did,'title':title,'source':'本项目人工可审阅的模拟政策，非真实平台规定','facts':[{'id':did+':a','text':a},{'id':did+':b','text':b}]})
        dev.extend([{'id':did+'-single','question':q1,'required':[[did+':a']],'type':'single'},
                    {'id':did+'-combined','question':q3,'required':[[did+':a'],[did+':b']],'type':'multiple'}])
        held.append({'id':did+'-paraphrase','question':q2,'required':[[did+':b']],'type':'paraphrase'})
    for i,q in enumerate(['是否承诺所有订单次日送达？','店铺是否支持比特币付款？','退款能否直接转给其他人的账户？','购买商品是否自动获得终身免费维修？']):
        (dev if i%2==0 else held).append({'id':f'unknown-{i}','question':q,'required':[],'type':'unanswerable'})
    regression=[]
    for file in ['e2e_cases.json','e2e_invoice_cases.json']:
        content=json.loads((ROOT/'baseline/rag'/file).read_text(encoding='utf-8'))
        if isinstance(content,dict):
            content=content.get('cases',[])
        for row in content:
            regression.append({'id':row['id'],'question':row['question'],'required':[[eid] for eid in row.get('required_citations',[])],
                               'type':'original','expected_status':row.get('expected_status'),'label_note':'沿用原题引用标签；澄清/不足题不是普通完整答案评测'})
    dump('corpus.json',docs)
    dump('original-corpus.json',list(grouped.values()))
    dump('development.json',dev)
    dump('heldout.json',held)
    dump('regression.json',regression)
    manifests={p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in (ROOT/'data').glob('*.json') if p.name!='manifest.json'}
    dump('manifest.json',{'version':1,'date':'2026-11-03','policy_documents':len(docs),'new_simulated_documents':len(POLICIES),'development_cases':len(dev),'heldout_cases':len(held),'regression_cases':len(regression),'files':manifests,'limitations':['合成模拟数据，不代表生产分布','同主题开发/留出题测试表述泛化，不是未见主题泛化','原回归集单独使用原语料','不以此题集推断生产准确率']})
    print(json.dumps({'documents':len(docs),'development':len(dev),'heldout':len(held),'regression':len(regression)},ensure_ascii=False))


if __name__=='__main__':
    main()
